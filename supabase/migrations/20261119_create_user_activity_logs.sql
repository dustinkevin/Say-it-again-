-- 1. Create public.user_activity_logs table to store user listening & shadowing activity with timestamps
CREATE TABLE IF NOT EXISTS public.user_activity_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  sentence_id INTEGER NOT NULL,
  sentence_text TEXT,
  speaker TEXT,
  step SMALLINT NOT NULL DEFAULT 1,
  activity_type TEXT NOT NULL CHECK (activity_type IN ('listen', 'shadow')),
  listen_count INTEGER NOT NULL DEFAULT 0,
  shadow_count INTEGER NOT NULL DEFAULT 0,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Index for fast per-user chronological queries
CREATE INDEX IF NOT EXISTS idx_user_activity_logs_user_time
  ON public.user_activity_logs (user_id, recorded_at DESC);

-- 2. Explicit GRANT SQL for PostgREST API access (anon, authenticated)
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.user_activity_logs TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

-- 3. Enable RLS (Row Level Security)
ALTER TABLE public.user_activity_logs ENABLE ROW LEVEL SECURITY;

-- 4. Authenticated-only RLS Policies
DROP POLICY IF EXISTS "Authenticated users can select own activity logs" ON public.user_activity_logs;
CREATE POLICY "Authenticated users can select own activity logs"
  ON public.user_activity_logs
  FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Authenticated users can insert own activity logs" ON public.user_activity_logs;
CREATE POLICY "Authenticated users can insert own activity logs"
  ON public.user_activity_logs
  FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Authenticated users can update own activity logs" ON public.user_activity_logs;
CREATE POLICY "Authenticated users can update own activity logs"
  ON public.user_activity_logs
  FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Authenticated users can delete own activity logs" ON public.user_activity_logs;
CREATE POLICY "Authenticated users can delete own activity logs"
  ON public.user_activity_logs
  FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);
